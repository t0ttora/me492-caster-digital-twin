function [g,d,p] = m2_load_parameters()
% Named JSON is authoritative. Numeric vector is only a Simulink transport adapter.
root=fileparts(mfilename('fullpath'));
d=jsondecode(fileread(fullfile(root,'dynamics_si.json')));
g=jsondecode(fileread(fullfile(root,d.geometry_file)));
assert(strcmp(d.units,'SI') && strcmp(d.parameter_status,'provisional_synthetic'));
assert(strcmp(g.units,'SI') && strcmp(g.parameter_status,'provisional_synthetic'));
assert(g.drive_radius_m>0 && g.caster_radius_m>0 && g.caster_trail_m>0 && g.drive_track_m>0);
assert(g.caster_pivot_m(1)+g.caster_trail_m<0,'Caster must remain behind drive axle.');
p=[d.body_lumped_mass_kg;d.caster_lumped_mass_kg;d.body_yaw_inertia_kgm2; ...
   d.caster_swivel_inertia_com_kgm2;d.drive_roll_inertia_kgm2;d.caster_roll_inertia_kgm2; ...
   d.body_com_m(:);g.drive_radius_m;g.drive_track_m;g.caster_radius_m;g.caster_trail_m; ...
   g.caster_pivot_m(1:2);d.gravity_mps2;d.drive_friction_coefficient;d.caster_friction_coefficient; ...
   d.drive_long_slip_damping_Nspm;d.drive_lat_slip_damping_Nspm; ...
   d.caster_long_slip_damping_Nspm;d.caster_lat_slip_damping_Nspm; ...
   d.drive_rolling_resistance_coefficient;d.caster_rolling_resistance_coefficient; ...
   d.drive_roll_viscous_NmspRad;d.caster_roll_viscous_NmspRad; ...
   d.swivel_bearing_viscous_NmspRad;d.swivel_bearing_coulomb_Nm; ...
   d.rolling_regularization_radps;d.swivel_regularization_radps; ...
   d.caster_bore_effective_radius_m;d.bore_regularization_radps];
assert(numel(p)==32 && all(isfinite(p)) && all(p([1:6 10:13 16 19:22 29:30 32])>0));
assert(all(p([17:18 23:28 31])>=0));
assert(d.solver_step_s>0 && d.command_sample_dt_s>0 && d.result_sample_dt_s>0);
assert(abs(d.command_sample_dt_s/d.solver_step_s-round(d.command_sample_dt_s/d.solver_step_s))<1e-9);
% Reject an unsupported COM, rather than clipping negative contact loads.
for phi=linspace(-pi,pi,361)
    x=zeros(13,1); x(4)=phi; [~,c]=m2_contact(x,p,1);
    assert(all(c(7:9)>0),'ME492:UnsupportedCOM','COM leaves the support triangle.');
end
end

